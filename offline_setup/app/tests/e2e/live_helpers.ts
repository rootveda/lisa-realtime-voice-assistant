import type { APIRequestContext } from "@playwright/test";

export function isLiveBaseConfigured(): boolean {
  return typeof process.env.PLAYWRIGHT_BASE_URL === "string" && process.env.PLAYWRIGHT_BASE_URL.trim().length > 0;
}

export async function getLlmModelForChat(request: APIRequestContext): Promise<string> {
  try {
    const r = await request.get("/api/runtime-status");
    if (!r.ok()) return "gemma4:e2b-it-q4_K_M";
    const j = (await r.json()) as { models?: { llm_model?: string } };
    const m = (j?.models?.llm_model || "").trim();
    return m || "gemma4:e2b-it-q4_K_M";
  } catch {
    return "gemma4:e2b-it-q4_K_M";
  }
}

